_SHELL_LETTERS = {"s": 0, "p": 1, "d": 2, "f": 3}


def parse_stoner(text):
    """``"Ni:d=0.12,O:p=0.0"`` -> ``{28: {2: 0.12}, 8: {1: 0.0}}`` (Hartree)."""
    from ase.data import atomic_numbers

    out = {}
    for item in filter(None, (t.strip() for t in text.split(","))):
        try:
            elem, rest = item.split(":")
            shell, value = rest.split("=")
            Z = atomic_numbers[elem.strip()]
            l = _SHELL_LETTERS[shell.strip().lower()]
            out.setdefault(Z, {})[l] = float(value)
        except (ValueError, KeyError) as err:
            raise ValueError(
                f"Bad --stoner entry {item!r}; expected e.g. 'Ni:d=0.12'"
            ) from err
    return out


