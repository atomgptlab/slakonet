@contextlib.contextmanager
def _green_with_all_bands():
    """TB2J's TBGreen drops every band above E_F + 5.1 eV before building
    G(k, E). The occupied-empty mixing that gives superexchange then
    disappears whenever the empty (minority) d band lies higher, and J
    becomes dependent on where E_F sits in the gap. A minimal tight-binding
    basis is small, so keep all bands. TB2J itself is restored on exit."""
    from TB2J import green

    original = green.TBGreen._reduce_eigens

    def keep_all(self, evals, evecs, emin, emax):
        return original(self, evals, evecs, emin, np.inf)

    green.TBGreen._reduce_eigens = keep_all
    try:
        yield
    finally:
        green.TBGreen._reduce_eigens = original


def gen_exchange_slakonet(
    atoms,
    magnetic_elements,
    spin_model=None,
    model=None,
    magnetic_model="hubbard",
    hubbard_U=None,
    stoner_I=None,
    initial_moments=None,
    scf_kmesh=(8, 8, 8),
    use_scc=False,
    scc_legacy=False,
    target_moments=None,
    stoner_table="fitted",
    kT=0.025,
    kmesh=(7, 7, 7),
    emin=-14.0,
    emax=0.0,
    nz=100,
    Rcut=None,
    exclude_orbs=(),
    index_magnetic_atoms=None,
    orb_decomposition=False,
    nproc=1,
    output_path="TB2J_results",
    description=None,
    keep_all_bands=True,
    verbose=True,
):
    """slakonet -> TB2J collinear exchange (``ExchangeCL2``).

    ``emin``/``emax`` are relative to the Fermi level (eV), as in the other
    TB2J interfaces. Pass a prebuilt ``spin_model`` to skip the
    self-consistency.

    ``magnetic_model``: "hubbard" (default, recommended) = atomic Stoner +
    orbital-resolved +U with the anion-dependent U fitted to experiment + SCC
    (``slakonet.hubbard_spin``); "stoner" = rigid Stoner exchange with the
    fitted per-site table (``build_spin_model``). With ``target_moments`` ({symbol: mu_B}) the d-shell
    Stoner I of those elements is calibrated to reproduce the moments
    (``calibrate_stoner``); ``stoner_I`` then only sets the other shells.
    ``keep_all_bands`` (default) builds the Green's function from every band
    instead of TB2J's cut at E_F + 5.1 eV (see ``_green_with_all_bands``). Returns ``(exchange, spin_model)``; the results are
    written to ``output_path`` (``TB2J.pickle``, ``exchange.out``, ...).
    """
    from TB2J.exchangeCL2 import ExchangeCL2

    if magnetic_model not in ("hubbard", "stoner"):
        raise ValueError(
            f"magnetic_model must be 'hubbard' or 'stoner', got {magnetic_model!r}"
        )
    if spin_model is None and magnetic_model == "hubbard":
        from slakonet.hubbard_spin import build_hubbard_model

        spin_model = build_hubbard_model(
            atoms,
            model=model,
            hubbard_U=hubbard_U,
            stoner_I=stoner_I,
            initial_moments=initial_moments,
            magnetic_elements=magnetic_elements,
            kmesh=scf_kmesh,
            kT=kT,
            verbose=verbose,
        )
    if spin_model is None and target_moments:
        _, spin_model = calibrate_stoner(
            atoms,
            target_moments,
            model=model,
            stoner_I=stoner_I,
            initial_moments=initial_moments,
            kmesh=scf_kmesh,
            use_scc=use_scc,
            scc_legacy=scc_legacy,
            stoner_table=stoner_table,
            kT=kT,
            verbose=verbose,
        )
    elif spin_model is None:
        spin_model = build_spin_model(
            atoms,
            model=model,
            stoner_I=stoner_I,
            initial_moments=initial_moments,
            magnetic_elements=magnetic_elements,
            kmesh=scf_kmesh,
            use_scc=use_scc,
            scc_legacy=scc_legacy,
            stoner_table=stoner_table,
            kT=kT,
            verbose=verbose,
        )
    # TB2J rounds the mesh up to odd sizes (always contains Gamma).
    from TB2J.kpoints import monkhorst_pack

    odd = [k // 2 * 2 + 1 for k in kmesh]
    check_overlap(
        spin_model.Rlist,
        spin_model.SR,
        monkhorst_pack(odd, gamma_center=True),
        spin_model.labels,
    )
    tb_up, tb_dn = spin_model.to_tb2j_models()

    if description is None:
        description = (
            "Input from slakonet (Slater-Koster TB + Stoner exchange"
            f"{' + SCC' if use_scc else ''}).\n"
            f"Spin-SCF converged: {spin_model.converged} "
            f"({spin_model.n_iter} iterations)\n"
            f"Moments (mu_B): {np.round(spin_model.moments, 3).tolist()}\n"
            f"Stoner I (Ha) {{Z: {{l: I}}}}: {spin_model.stoner_I}\n"
            f"Site d-shell I from the fitted table (Ha) {{atom: I}}: {spin_model.site_stoner_I}\n"
            + (
                f"Hubbard U_eff on d shells (Ha) {{atom: U}}: {spin_model.hubbard_U}\n"
                if spin_model.hubbard_U
                else ""
            )
            + (
                f"Calibrated to target moments (mu_B): {target_moments}\n"
                if target_moments
                else ""
            )
        )

    context = (
        _green_with_all_bands() if keep_all_bands else contextlib.nullcontext()
    )
    with context:
        exchange = ExchangeCL2(
            tbmodels=(tb_up, tb_dn),
            atoms=spin_model.atoms,
            basis=spin_model.labels,
            efermi=spin_model.efermi,
            magnetic_elements=list(magnetic_elements),
            kmesh=list(kmesh),
            emin=emin,
            emax=emax,
            nz=nz,
            Rcut=Rcut,
            exclude_orbs=list(exclude_orbs),
            index_magnetic_atoms=index_magnetic_atoms,
            orb_decomposition=orb_decomposition,
            nproc=nproc,
            output_path=output_path,
            description=description,
        )
        exchange.run(path=output_path)
    return exchange, spin_model


def compute_magnon_bands(
    path="TB2J_results", kpath=None, npoints=300, filename=None
):
    """Magnon band structure from a TB2J results directory (J_iso only).

    The collinear order is taken from the signed moments TB2J wrote, so AFM
    references work without extra input. ``kpath`` (e.g. ``"GXMG"``) defaults
    to the ASE path of the cell. Writes ``<filename>.png`` and ``.json``.
    """
    from TB2J.magnon.magnon3 import plot_magnon_bands_from_TB2J
    from TB2J.magnon.magnon_parameters import MagnonParameters

    params = MagnonParameters(
        path=path,
        filename=filename or f"{path}/magnon_bands.png",
        Jiso=True,
        Jani=False,
        DMI=False,
        SIA=False,
        kpath=kpath,
        npoints=npoints,
        show=False,
    )
    return plot_magnon_bands_from_TB2J(params)


