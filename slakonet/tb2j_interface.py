    from slakonet.optim import default_model

    model = (
        default_model(model_name=args.model) if args.model else default_model()
    )
    atoms = read(args.structure)
    gen_exchange_slakonet(
        atoms,
        args.elements,
        model=model,
        stoner_I=parse_stoner(args.stoner),
        initial_moments=args.magmoms,
        scf_kmesh=tuple(args.scf_kmesh),
        use_scc=args.scc,
        scc_legacy=args.scc_legacy,
        stoner_table=args.stoner_table,
        magnetic_model=args.magnetic_model,
        target_moments=(
            {
                k: float(v)
                for k, v in (t.split("=") for t in args.target_moment)
            }
            if args.target_moment
            else None
        ),
        kT=args.kT,
        kmesh=tuple(args.kmesh),
        emin=args.emin,
        emax=args.emax,
        nz=args.nz,
        Rcut=args.rcut,
        nproc=args.nproc,
        output_path=args.output_path,
    )
    if args.magnon:
        compute_magnon_bands(args.output_path, kpath=args.kpath)


