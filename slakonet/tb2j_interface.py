"""Interface between slakonet and TB2J (collinear exchange and magnons).

Pipeline
--------
1. Real-space Hamiltonian and overlap. slakonet only builds Bloch sums
   H(k), S(k). The support of H(R) is the finite set of image cells inside
   the SK cutoff (``Periodic.cellvec_neighbour``, |n_i| <= n_max), so H(k) on a
   Gamma-centred grid with N_i = 2 n_max,i + 1 points is inverted *exactly*
   (no aliasing) to

       H(R) = 1/N_k sum_k H(k) exp(-2 pi i k.R),

   in the same gauge TB2J uses (H(k) = sum_R H(R) exp(+2 pi i k.R)).

2. Collinear spin-polarized model, identical to ``slakonet.magnetism``
   (Stoner-like on-site exchange) plus the optional SCC charge shift of
   ``slakonet.scc``:

       H_sigma(R) = H0(R) + 1/2 S(R) o (deps_mu + deps_nu)
                    + sigma delta_{R,0} diag(V_mu),
       V_mu = -1/2 I_l(Z) m_a.

   Moments m_a (and charges, if SCC) are converged self-consistently on a
   uniform k-mesh, directly from these real-space matrices, so the model
   handed to TB2J is exactly the one that was converged.

3. The two spin channels are wrapped as HamiltonIO ``LCAOHamiltonian``
   objects (eV, non-orthogonal) and passed to TB2J ``ExchangeCL2``. The
   exchange splitting TB2J uses is Delta = H_up(R=0) - H_dn(R=0) = 2 diag(V).

Only the collinear case is covered: J_iso (and TB2J's biquadratic term).
DMI and anisotropic exchange need a spinor (SOC) Hamiltonian.
"""

from __future__ import annotations

import contextlib
from dataclasses import dataclass, field

import numpy as np
import torch

from slakonet.magnetism import (
    DEFAULT_STONER_I,
    _build_stoner_shift_per_orbital,
    _orbital_to_shell_l_and_atom,
    _shared_fermi_and_occ,
)
from slakonet.slaterkoster import hs_matrix

# Real-harmonic order used by the SKF / slakonet basis (see soc.py).
_ORBITAL_NAMES = {
    0: ["s"],
    1: ["py", "pz", "px"],
    2: ["dxy", "dyz", "dz2", "dxz", "dx2-y2"],
    3: ["f-3", "f-2", "f-1", "f0", "f1", "f2", "f3"],
}


# ---------------------------------------------------------------------------
# 1. Real-space H(R), S(R)
# ---------------------------------------------------------------------------
def _gamma_grid(n_per_dir):
    axes = [np.arange(n) / n for n in n_per_dir]
    return np.stack(np.meshgrid(*axes, indexing="ij"), -1).reshape(-1, 3)


def _mp_grid(n_per_dir):
    """Monkhorst-Pack grid, (i + 1/2)/N, as generated by slakonet's Periodic."""
    axes = [(np.arange(n) + 0.5) / n for n in n_per_dir]
    return np.stack(np.meshgrid(*axes, indexing="ij"), -1).reshape(-1, 3)


def extract_real_space_hs(calc, max_chunk_bytes=2**30):
    """Exact real-space H(R) and S(R) of a slakonet ``SimpleDftb``.

    Parameters
    ----------
    calc : SimpleDftb
        Any instance (k-points or k-lines); ``calc.calculate()`` is not needed.
        ``calc.periodic`` k-points are restored on return.
    max_chunk_bytes : int
        Memory bound for one batch of H(k) matrices.

    Returns
    -------
    Rlist : ndarray [nR, 3] int, lattice vectors in reduced coordinates.
    HR : ndarray [nR, Norb, Norb] float64, Hartree.
    SR : ndarray [nR, Norb, Norb] float64.
    """
    periodic = calc.periodic
    cells = periodic.cellvec_neighbour[0].T.detach().cpu().numpy()
    cells = np.rint(cells).astype(int)
    Rlist = np.unique(np.concatenate([cells, -cells]), axis=0)
    n_max = np.abs(Rlist).max(axis=0)
    kgrid = _gamma_grid(2 * n_max + 1)
    nk = len(kgrid)

    norb = int(calc.basis.orbs_per_atom.sum())
    chunk = max(1, int(max_chunk_bytes // (2 * 16 * norb * norb)))

    HR = np.zeros((len(Rlist), norb, norb), dtype=complex)
    SR = np.zeros_like(HR)
    saved_kpoints, saved_nk = periodic.kpoints, periodic.n_kpoints
    try:
        for start in range(0, nk, chunk):
            kpts = kgrid[start : start + chunk]
            periodic.kpoints = torch.tensor(
                kpts, dtype=saved_kpoints.dtype, device=saved_kpoints.device
            ).unsqueeze(0)
            periodic.n_kpoints = torch.tensor([len(kpts)])
            with torch.no_grad():
                Hk = hs_matrix(periodic, calc.basis, calc.h_feed)[0]
                Sk = hs_matrix(periodic, calc.basis, calc.s_feed)[0]
            phase = np.exp(-2j * np.pi * kpts @ Rlist.T) / nk  # [nk, nR]
            HR += np.einsum("abk,kr->rab", Hk.cpu().numpy(), phase)
            SR += np.einsum("abk,kr->rab", Sk.cpu().numpy(), phase)
    finally:
        periodic.kpoints, periodic.n_kpoints = saved_kpoints, saved_nk

    # Slater-Koster matrices are real in real space; the imaginary part is
    # round-off of the float32 geometry. Enforce H(-R) = H(R)^T exactly.
    imag = max(np.abs(HR.imag).max(), np.abs(SR.imag).max())
    if imag > 1e-5:
        raise RuntimeError(
            f"H(R)/S(R) has an imaginary part of {imag:.2e}; the Fourier "
            "inversion is not exact (k-grid smaller than the H(R) support?)."
        )
    HR, SR = HR.real, SR.real
    index = {tuple(R): i for i, R in enumerate(Rlist)}
    minus = np.array([index[tuple(-R)] for R in Rlist])
    HR = 0.5 * (HR + HR[minus].transpose(0, 2, 1))
    SR = 0.5 * (SR + SR[minus].transpose(0, 2, 1))
    return Rlist, HR, SR


def orbital_labels(calc, atoms):
    """TB2J basis labels ``"<Sym><n>|<orb>"`` (``Ni1|dxy``), in slakonet
    orbital order, plus the atom index and angular momentum per orbital."""
    atom_idx, ls = _orbital_to_shell_l_and_atom(calc.basis)
    atom_idx = atom_idx.tolist()
    ls = ls.tolist()
    symbols = atoms.get_chemical_symbols()
    counter, names = {}, []
    for s in symbols:
        counter[s] = counter.get(s, 0) + 1
        names.append(f"{s}{counter[s]}")

    labels = []
    m = 0
    for iorb, (ia, l) in enumerate(zip(atom_idx, ls)):
        new_shell = (
            iorb == 0
            or ia != atom_idx[iorb - 1]
            or l != ls[iorb - 1]
            or m == 2 * l + 1
        )
        m = 0 if new_shell else m
        labels.append(f"{names[ia]}|{_ORBITAL_NAMES[l][m]}")
        m += 1
    return labels, np.array(atom_idx), np.array(ls)


# ---------------------------------------------------------------------------
# 2. Spin-polarized (+ SCC) self-consistency in real space
# ---------------------------------------------------------------------------
def _bloch(Rlist, XR, kpts):
    """X(k) = sum_R X(R) exp(2 pi i k.R); returns [Nk, N, N] complex."""
    phase = torch.exp(2j * np.pi * (kpts @ Rlist.T))  # [Nk, nR]
    return torch.einsum("kr,rab->kab", phase, XR.to(torch.complex128))


def _eigh(A):
    """Batched Hermitian eigh. torch's complex LAPACK driver can fail to
    converge on matrices with many exactly degenerate eigenvalues (high
    symmetry k-points); numpy's driver handles them, so fall back to it."""
    try:
        return torch.linalg.eigh(A)
    except RuntimeError:
        w, v = np.linalg.eigh(A.detach().cpu().numpy())
        return torch.from_numpy(w), torch.from_numpy(v)


def check_overlap(Rlist, SR, kpts, labels, tol=1e-6):
    """Raise ValueError if S(k) is not positive definite at some k-point.

    Some slakonet parameter sets give an unphysical (non-Gram) overlap for
    dense packings of diffuse orbitals (e.g. K in KCoF3 at Gamma). The error
    names the k-point and the elements carrying the offending mode."""
    R = torch.as_tensor(np.asarray(Rlist), dtype=torch.float64)
    Sk = _bloch(
        R,
        torch.as_tensor(SR),
        torch.as_tensor(np.asarray(kpts), dtype=torch.float64),
    )
    evals, evecs = _eigh(Sk)
    ik = int(torch.argmin(evals[:, 0]))
    if evals[ik, 0] > tol:
        return
    weight = evecs[ik, :, 0].abs() ** 2
    elements = np.array(
        [lab.split("|")[0].rstrip("0123456789") for lab in labels]
    )
    share = {
        str(e): round(float(weight[torch.as_tensor(elements == e)].sum()), 2)
        for e in sorted(set(elements))
    }
    raise ValueError(
        f"The slakonet overlap matrix S(k) is not positive definite at "
        f"k = {np.round(np.asarray(kpts)[ik], 4).tolist()} (lowest eigenvalue "
        f"{float(evals[ik, 0]):.3e}); weight of that mode by element: {share}. "
        "The Slater-Koster overlap of this parameter set is unphysical for this "
        "structure, so no Green's function can be built."
    )


def _solve_generalized(Hk, Lk_inv):
    """Batched H c = e S c through the Cholesky factor of S."""
    Ht = Lk_inv @ Hk @ Lk_inv.conj().transpose(-1, -2)
    Ht = 0.5 * (Ht + Ht.conj().transpose(-1, -2))
    e, v = _eigh(Ht)
    return e, Lk_inv.conj().transpose(-1, -2) @ v  # [Nk,Nb], [Nk,Norb,Nb]


def _orbital_populations(C, Sk, occ, k_weights):
    """Mulliken populations per orbital, [Norb]. occ: [Nk, Nb]."""
    SC = Sk @ C
    pop = (C.conj() * SC).real  # [Nk, Norb, Nb]
    return torch.einsum("kob,kb,k->o", pop, occ, k_weights)


@dataclass
class SlakonetSpinModel:
    """Converged collinear slakonet model, ready for TB2J."""

    atoms: object
    Rlist: np.ndarray  # [nR, 3] int
    HR_up: np.ndarray  # [nR, Norb, Norb] eV
    HR_dn: np.ndarray  # [nR, Norb, Norb] eV
    SR: np.ndarray  # [nR, Norb, Norb]
    labels: list
    efermi: float  # eV
    moments: np.ndarray  # [Natom] mu_B
    charges: np.ndarray  # [Natom] Mulliken electrons
    nelectron: float
    converged: bool
    n_iter: int
    history: list = field(default_factory=list)
    stoner_I: dict = field(
        default_factory=dict
    )  # {Z: {l: I_Ha}} element level
    site_stoner_I: dict = field(
        default_factory=dict
    )  # {atom: I_d} fitted table, overrides
    hubbard_U: dict = field(
        default_factory=dict
    )  # {atom: U_eff (Ha)}, +U model
    # converged +U potentials (eV): 'scc_shift' [Natom], 'stoner_V' [Norb] (spin up,
    # spin down = -V), 'U_up'/'U_dn' {atom: (orbital indices, 5x5)}; used to
    # train the SK parameters with a frozen spin potential
    potentials: dict = field(default_factory=dict)

    @property
    def nbasis(self):
        return self.HR_up.shape[-1]

    def bloch(self, kpts):
        """H_up(k), H_dn(k) (eV) and S(k) at reduced k-points [Nk, 3]."""
        R = torch.as_tensor(self.Rlist, dtype=torch.float64)
        k = torch.as_tensor(np.asarray(kpts), dtype=torch.float64)
        return tuple(
            _bloch(R, torch.as_tensor(X), k).numpy()
            for X in (self.HR_up, self.HR_dn, self.SR)
        )

    def to_tb2j_models(self):
        """Two HamiltonIO ``LCAOHamiltonian`` (spin up, spin down)."""
        from HamiltonIO.lcao_hamiltonian import LCAOHamiltonian

        models = []
        for HR in (self.HR_up, self.HR_dn):
            tb = LCAOHamiltonian(
                HR=HR,
                SR=self.SR,
                Rlist=self.Rlist,
                nbasis=self.nbasis,
                atoms=self.atoms,
                nspin=1,
            )
            tb._name = "slakonet"
            tb.basis = self.labels
            models.append(tb)
        return tuple(models)


def equivalent_atom_classes(atoms, symprec=1e-3):
    """Crystallographic equivalence classes (spglib ``equivalent_atoms``) of
    the non-magnetic structure: one representative index per atom."""
    import spglib

    cell = (atoms.cell.array, atoms.get_scaled_positions(), atoms.numbers)
    dataset = spglib.get_symmetry_dataset(cell, symprec=symprec)
    if dataset is None:
        raise RuntimeError(
            "spglib could not determine the symmetry of the structure."
        )
    return torch.as_tensor(
        np.asarray(dataset.equivalent_atoms), dtype=torch.long
    )


def _class_mean(x, classes, keep_sign=False):
    """Average x over equivalent atoms. With keep_sign, average |x| and keep
    each atom's sign (the collinear order)."""
    n = torch.zeros(int(classes.max()) + 1, dtype=x.dtype)
    n.scatter_add_(0, classes, torch.ones_like(x))
    val = x.abs() if keep_sign else x
    mean = torch.zeros_like(n).scatter_add_(0, classes, val) / n.clamp_min(1)
    return torch.sign(x) * mean[classes] if keep_sign else mean[classes]


def _default_initial_moments(atomic_numbers, magnetic_indices):
    m = np.zeros(len(atomic_numbers))
    m[list(magnetic_indices)] = 2.0
    return m


def build_spin_model(
    atoms,
    model=None,
    stoner_I=None,
    initial_moments=None,
    magnetic_elements=None,
    kmesh=(8, 8, 8),
    use_scc=False,
    stoner_table="fitted",
    kT=0.025,
    max_iter=200,
    mixing=0.3,
    tol=1e-5,
    symmetrize=True,
    scc_legacy=False,
    mixer="anderson",
    cutoff=10.0,
    device="cpu",
    verbose=True,
):
    """Build the converged collinear slakonet model of ``atoms``.

    Parameters
    ----------
    atoms : ase.Atoms
        Crystal structure (the magnetic cell, e.g. an AFM supercell).
    model : slakonet model, optional
        Defaults to ``slakonet.optim.default_model()``.
    stoner_I : dict {Z: {l: I_Ha}}, optional
        Explicit Stoner parameters; they take precedence over the table.
    stoner_table : {"fitted", "atomic"}
        Source of the d-shell I when ``stoner_I`` does not give it. "fitted"
        (default): per-site value from ``slakonet.stoner_tables``, learned
        from experimental exchange constants and chosen by the automatic
        site class (element, ionic/metallic environment, formal oxidation);
        elements outside the table use the atomic values. "atomic": the
        atomic values of ``slakonet.magnetism.DEFAULT_STONER_I``.
    initial_moments : sequence [Natom], optional
        Starting moments (mu_B, signed; sets the collinear order). Defaults
        to +2 on the atoms of ``magnetic_elements`` (FM start).
    magnetic_elements : list[str], optional
        Only used for the default initial moments.
    kmesh : 3 ints
        Monkhorst-Pack mesh of the spin/charge self-consistency (same
        convention as slakonet's ``kpoints``).
    use_scc : bool
        Also converge SCC charges (``slakonet.scc`` shift).
    scc_legacy : bool
        Use the original slakonet SCC (U of the highest-l shell, cluster
        Klopman-Ohno gamma) instead of the occupied-shell U with the periodic
        DFTB gamma (Ewald).
    mixer : {"anderson", "linear"}
        Mixing of the moments (and charges).
    kT : float
        Fermi smearing (eV) of the self-consistency.
    max_iter, mixing, tol :
        Mixing fraction; ``tol`` on max |Delta m|, |Delta q| (electrons).
    symmetrize : bool
        Keep |m| (and Delta q) equal on crystallographically equivalent atoms
        at every iteration, the sign of m following the collinear order. The
        Stoner model has no Coulomb penalty for charge transfer, so without
        it equivalent sites can drift into an unphysical charge/spin
        disproportionation (e.g. rutile FeF2: 6 and 8 electrons on the two
        Fe). Set False for genuinely inequivalent orders; a warning is
        printed if equivalent atoms end with different moments.

    Returns
    -------
    SlakonetSpinModel
    """
    from slakonet.atoms import Geometry
    from slakonet.main import SimpleDftb

    if model is None:
        from slakonet.optim import default_model

        model = default_model()

    calc = SimpleDftb(
        Geometry.from_ase_atoms([atoms]),
        model,
        cutoff=cutoff,
        kpoints=torch.tensor([1, 1, 1]),
        device=device,
        compute_forces=False,
        include_dos_data=False,
        repulsive=False,
        kT=kT,
    )
    H2E = calc.H2E
    Rlist_np, HR0_np, SR_np = extract_real_space_hs(calc)
    labels, orb_atom_np, _ = orbital_labels(calc, atoms)

    Rlist = torch.as_tensor(Rlist_np, dtype=torch.float64)
    HR0 = torch.as_tensor(HR0_np)
    SR = torch.as_tensor(SR_np)
    iR0 = int(np.where(~Rlist_np.any(axis=1))[0][0])
    orb_atom = torch.as_tensor(orb_atom_np)
    natom = len(atoms)

    kpts = torch.as_tensor(_mp_grid(kmesh), dtype=torch.float64)
    k_weights = torch.full((len(kpts),), 1.0 / len(kpts), dtype=torch.float64)
    check_overlap(
        Rlist_np, SR_np, np.vstack([np.zeros((1, 3)), kpts.numpy()]), labels
    )
    Sk = _bloch(Rlist, SR, kpts)
    Lk_inv = torch.linalg.inv(torch.linalg.cholesky(Sk))

    stoner_full = dict(DEFAULT_STONER_I)
    for Z, shells in (stoner_I or {}).items():
        stoner_full[Z] = {**stoner_full.get(Z, {}), **shells}

    Zs = atoms.get_atomic_numbers()
    # per-site d-shell I from the fitted table, unless given explicitly
    site_I = {}
    if stoner_table == "fitted":
        from slakonet.stoner_tables import fitted_site_stoner_I

        explicit = {
            int(Z) for Z, shells in (stoner_I or {}).items() if 2 in shells
        }
        site_I = {
            i: I
            for i, I in fitted_site_stoner_I(atoms).items()
            if int(Zs[i]) not in explicit
        }
    elif stoner_table != "atomic":
        raise ValueError(
            f"stoner_table must be 'fitted' or 'atomic', got {stoner_table!r}"
        )
    _, _, orb_l_np = orbital_labels(calc, atoms)
    d_orbitals = {
        a: np.where((orb_atom_np == a) & (orb_l_np == 2))[0] for a in site_I
    }
    if initial_moments is None:
        mag = set(magnetic_elements or [])
        mag_idx = [
            i for i, s in enumerate(atoms.get_chemical_symbols()) if s in mag
        ]
        if not mag_idx:
            raise ValueError("Give initial_moments or magnetic_elements.")
        initial_moments = _default_initial_moments(Zs, mag_idx)
    m = torch.as_tensor(np.asarray(initial_moments, dtype=float)).flatten()
    if m.shape[0] != natom:
        raise ValueError(
            f"initial_moments has {m.shape[0]} entries, Natom={natom}"
        )

    classes = equivalent_atom_classes(atoms)
    if symmetrize:
        m = _class_mean(m, classes, keep_sign=True)

    nelec = float(calc.nelectron.flatten()[0])
    dq = torch.zeros(natom, dtype=torch.float64)
    if use_scc:
        from slakonet.scc import (
            atom_U_from_skf,
            build_gamma_matrix,
            build_gamma_matrix_periodic,
            reference_charges,
        )

        U = []
        for Z in Zs.tolist():
            u = atom_U_from_skf(
                calc.updated_skfs, int(Z), calc.shell_dict, legacy=scc_legacy
            )
            if u is None:
                raise ValueError(
                    f"No Hubbard U in the SKF of Z={Z}; cannot run SCC."
                )
            U.append(u)
        U = torch.tensor(U, dtype=torch.float64)
        positions = calc.geometry.positions[0].to(torch.float64).cpu()
        if scc_legacy:
            gamma = build_gamma_matrix(positions, U)
        else:
            gamma = build_gamma_matrix_periodic(
                positions, calc.geometry.cell[0], U
            )
        q_ref = reference_charges(
            torch.as_tensor(Zs), calc.updated_skfs, calc.shell_dict
        ).to(torch.float64)

    kT_Ha = kT / H2E
    history, converged = [], False
    if mixer == "anderson":
        from slakonet.scc import AndersonMixer

        anderson = AndersonMixer(alpha=mixing)
    elif mixer != "linear":
        raise ValueError(
            f"mixer must be 'anderson' or 'linear', got {mixer!r}"
        )

    def hamiltonians(m, dq):
        HR = HR0.clone()
        if use_scc:
            deps = (gamma @ dq)[orb_atom]
            HR = HR + 0.5 * SR * (deps[:, None] + deps[None, :])
        V = _build_stoner_shift_per_orbital(calc.basis, m, stoner_full).cpu()
        for a, I_a in site_I.items():
            V[d_orbitals[a]] = -0.5 * I_a * m[a]
        HR_up, HR_dn = HR.clone(), HR.clone()
        HR_up[iR0] += torch.diag(V)
        HR_dn[iR0] -= torch.diag(V)
        return HR_up, HR_dn

    for it in range(max_iter):
        HR_up, HR_dn = hamiltonians(m, dq)
        e_up, C_up = _solve_generalized(_bloch(Rlist, HR_up, kpts), Lk_inv)
        e_dn, C_dn = _solve_generalized(_bloch(Rlist, HR_dn, kpts), Lk_inv)
        mu, f_up, f_dn = _shared_fermi_and_occ(
            e_up.T, e_dn.T, k_weights, nelec, kT=kT_Ha
        )
        p_up = _orbital_populations(
            C_up, Sk, f_up.T.to(torch.float64), k_weights
        )
        p_dn = _orbital_populations(
            C_dn, Sk, f_dn.T.to(torch.float64), k_weights
        )
        m_new = torch.zeros(natom, dtype=torch.float64).scatter_add_(
            0, orb_atom, p_up - p_dn
        )
        q = torch.zeros(natom, dtype=torch.float64).scatter_add_(
            0, orb_atom, p_up + p_dn
        )
        if use_scc:
            dq_new = q - q_ref
        if symmetrize:
            # The k-mesh need not respect the symmetry exactly; drop that
            # O(1e-4) noise so it neither sets a floor on the residual nor
            # enters the mixing.
            m_new = _class_mean(m_new, classes, keep_sign=True)
            if use_scc:
                dq_new = _class_mean(dq_new, classes)
        res = (m_new - m).abs().max().item()
        if use_scc:
            res = max(res, (dq_new - dq).abs().max().item())
        history.append(
            {
                "iter": it,
                "residual": res,
                "M_tot": float(m_new.sum()),
                "mu_eV": mu * H2E,
            }
        )
        if verbose:
            print(
                f"[slakonet spin-SCF] iter {it:3d}  residual={res:.3e}  "
                f"M_tot={float(m_new.sum()):+.4f}  mu={mu * H2E:.4f} eV"
            )
        if res < tol:
            converged = True
            break
        if mixer == "anderson":
            x_in = torch.cat([m, dq]) if use_scc else m
            x_out = torch.cat([m_new, dq_new]) if use_scc else m_new
            x = anderson(x_in, x_out)
            m, dq = (x[:natom], x[natom:]) if use_scc else (x, dq)
        else:
            m = (1.0 - mixing) * m + mixing * m_new
            if use_scc:
                dq = (1.0 - mixing) * dq + mixing * dq_new
        if symmetrize:
            m = _class_mean(m, classes, keep_sign=True)
            if use_scc:
                dq = _class_mean(dq, classes)

    if not converged:
        print(
            f"WARNING: spin-SCF not converged after {max_iter} iterations "
            f"(residual {res:.2e}); the model of the last iteration is used."
        )

    spread = (
        m_new.abs() - _class_mean(m_new, classes, keep_sign=True).abs()
    ).abs()
    if spread.max() > 0.05:
        print(
            "WARNING: crystallographically equivalent atoms have different "
            f"|moments| (max deviation {spread.max():.2f} mu_B): "
            f"{np.round(m_new.numpy(), 3).tolist()}"
        )

    # Insulator: any mu inside the gap satisfies the electron count and the
    # bisection stops at an arbitrary point, possibly next to a band edge.
    # Put it at mid-gap, away from the poles of the Green's function.
    e_all = torch.cat(
        [e_up.T.flatten(), e_dn.T.flatten()]
    )  # e: [Nk, Nb]; f: [Nb, Nk]
    f_all = torch.cat([f_up.flatten(), f_dn.flatten()])
    occupied, empty = e_all[f_all > 0.5], e_all[f_all <= 0.5]
    if (
        len(occupied)
        and len(empty)
        and empty.min() - occupied.max() > 4 * kT_Ha
    ):
        mu = 0.5 * float(occupied.max() + empty.min())

    # (HR_up, HR_dn, mu) of the last iteration are mutually consistent: mu
    # and the output moments come from exactly these Hamiltonians.
    return SlakonetSpinModel(
        atoms=atoms.copy(),
        Rlist=Rlist_np,
        HR_up=HR_up.numpy() * H2E,
        HR_dn=HR_dn.numpy() * H2E,
        SR=SR_np,
        labels=labels,
        efermi=float(mu * H2E),
        moments=m_new.numpy(),
        charges=q.numpy(),
        nelectron=nelec,
        converged=converged,
        n_iter=it + 1,
        history=history,
        stoner_I={
            int(Z): dict(stoner_full.get(int(Z), {})) for Z in set(Zs.tolist())
        },
        site_stoner_I={int(a): float(I) for a, I in site_I.items()},
    )


def calibrate_stoner(
    atoms,
    target_moments,
    model=None,
    stoner_I=None,
    initial_moments=None,
    shell=2,
    I_max=0.3,
    moment_tol=0.02,
    max_bisection=20,
    verbose=True,
    **spin_kwargs,
):
    """Find, element by element, the Stoner I_l that reproduces a target
    moment, and return the converged model.

    Parameters
    ----------
    target_moments : dict {symbol: mu_B}
        Target mean |m| of the atoms of each element (e.g. the experimental
        ordered moment).
    initial_moments : sequence [Natom], optional
        Signed starting moments; only the signs (the collinear order) are
        used, the magnitude is reset to the target. Default: all positive.
    shell : int
        Angular momentum whose I is calibrated (2 = d).
    I_max : float
        Upper bound of the search (Hartree).
    moment_tol : float
        Stop when |mean |m| - target| < moment_tol (mu_B).
    spin_kwargs :
        Passed to ``build_spin_model`` (kmesh, use_scc, symmetrize, ...).

    Returns
    -------
    (stoner_I, SlakonetSpinModel) : the calibrated {Z: {l: I}} and its model.
        If a target is above the saturation moment of the model, a warning is
        printed and the smallest I reaching 98 % of the saturation moment is
        used.
    """
    from ase.data import atomic_numbers

    if model is None:
        from slakonet.optim import default_model

        model = default_model()

    symbols = np.array(atoms.get_chemical_symbols())
    signs = np.ones(len(atoms))
    if initial_moments is not None:
        signs = np.sign(np.asarray(initial_moments, dtype=float))
    m0 = np.zeros(len(atoms))
    for elem, target in target_moments.items():
        idx = symbols == elem
        if not idx.any():
            raise ValueError(f"No {elem} atom in the structure.")
        if (signs[idx] == 0).any():
            raise ValueError(
                f"initial_moments must give a sign to every {elem} atom."
            )
        m0[idx] = signs[idx] * target

    stoner = {Z: dict(v) for Z, v in (stoner_I or {}).items()}

    def solve(I_values):
        for elem, I in I_values.items():
            stoner.setdefault(atomic_numbers[elem], {})[shell] = I
        sm = build_spin_model(
            atoms,
            model,
            stoner_I=stoner,
            initial_moments=m0,
            verbose=False,
            **spin_kwargs,
        )
        if (
            not sm.converged
            and spin_kwargs.get("mixer", "anderson") == "anderson"
        ):
            kw = {
                **spin_kwargs,
                "mixer": "linear",
                "mixing": 0.2,
                "max_iter": 600,
            }
            sm = build_spin_model(
                atoms,
                model,
                stoner_I=stoner,
                initial_moments=m0,
                verbose=False,
                **kw,
            )
        return sm

    def mean_moment(sm, elem):
        return float(np.abs(sm.moments[symbols == elem]).mean())

    I_values = {
        elem: DEFAULT_STONER_I.get(atomic_numbers[elem], {}).get(shell, 0.0)
        for elem in target_moments
    }
    sm = None
    # Gauss-Seidel over elements (one pass is enough for a single element).
    for _ in range(3 if len(target_moments) > 1 else 1):
        for elem, target in target_moments.items():
            # Bracket [lo, hi] with converged solutions, stepping I upwards.
            lo, hi, I = 0.0, None, max(I_values[elem], 0.01)
            samples = []  # converged (I, |m|)
            while I <= I_max:
                sm = solve({**I_values, elem: I})
                m = mean_moment(sm, elem)
                if sm.converged:
                    samples.append((I, m))
                if verbose:
                    print(
                        f"[calibrate] {elem}: I_{'spdf'[shell]}={I:.4f} Ha -> "
                        f"|m|={m:.3f} (target {target:.3f}, converged={sm.converged})"
                    )
                if sm.converged and m >= target - moment_tol:
                    hi = I
                    break
                if sm.converged:
                    lo = I
                I *= 1.4
            if hi is None:
                # Target above the saturation moment of the model (e.g. the
                # ionic 2S in a covalent oxide): take the onset of the
                # plateau, the smallest I reaching 98 % of the largest
                # moment, instead of inflating I without gaining moment.
                if not samples:
                    raise RuntimeError(
                        f"No converged spin-SCF while calibrating {elem}."
                    )
                m_sat = max(m for _, m in samples)
                I_values[elem] = min(
                    I for I, m in samples if m >= 0.98 * m_sat
                )
                print(
                    f"WARNING: {elem} target {target:.2f} mu_B is above the "
                    f"saturation moment of the model ({m_sat:.2f} mu_B); using "
                    f"I = {I_values[elem]:.4f} Ha (onset of the plateau)."
                )
                continue
            if abs(m - target) < moment_tol:
                I_values[elem] = hi
                continue
            for _ in range(max_bisection):
                mid = 0.5 * (lo + hi)
                sm = solve({**I_values, elem: mid})
                m = mean_moment(sm, elem)
                if verbose:
                    print(
                        f"[calibrate] {elem}: I_{'spdf'[shell]}={mid:.4f} Ha -> "
                        f"|m|={m:.3f} (target {target:.3f})"
                    )
                if sm.converged and abs(m - target) < moment_tol:
                    lo = hi = mid
                    break
                lo, hi = (
                    (mid, hi)
                    if (m < target or not sm.converged)
                    else (lo, mid)
                )
            I_values[elem] = 0.5 * (lo + hi)
    sm = solve(I_values)
    if verbose:
        for elem, target in target_moments.items():
            print(
                f"[calibrate] {elem}: I_{'spdf'[shell]} = {I_values[elem]:.4f} Ha, "
                f"|m| = {mean_moment(sm, elem):.3f} mu_B (target {target:.3f})"
            )
    return stoner, sm


